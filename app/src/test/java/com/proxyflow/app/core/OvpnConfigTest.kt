package com.proxyflow.app.core

import com.proxyflow.app.data.Protocol
import com.proxyflow.app.data.ProxyProfile
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

class OvpnConfigTest {
    private val ca = "<ca>\n-----BEGIN CERTIFICATE-----\nMIIBszCCAVmgAwIBAgIUQ\n-----END CERTIFICATE-----\n</ca>\n"

    private val typical = """
        client
        dev tun
        proto udp
        remote vpn.example.com 1194
        remote 203.0.113.9 443 tcp
        resolv-retry infinite
        nobind
        persist-key
        persist-tun
        auth-user-pass /etc/openvpn/creds.txt
        remote-cert-tls server
        cipher AES-256-GCM
        script-security 2
        up /etc/openvpn/update-resolv-conf
        down /etc/openvpn/update-resolv-conf
        block-outside-dns
        key-direction 1
        verb 3
    """.trimIndent() + "\n" + ca + "<tls-auth>\n-----BEGIN OpenVPN Static key V1-----\nabcdef\n-----END OpenVPN Static key V1-----\n</tls-auth>\n"

    @Test fun parsesTypicalProviderConfig() {
        val p = OvpnConfig.parse(typical)
        assertTrue(p.errors.toString(), p.errors.isEmpty())
        assertEquals(listOf(OvpnConfig.Remote("vpn.example.com", 1194, "udp"), OvpnConfig.Remote("203.0.113.9", 443, "tcp")), p.remotes)
        assertTrue(p.needsUserPass)
        assertTrue(p.hasTlsAuthOrCrypt)
        assertFalse(p.keyEncrypted)
        // dangerous / foreign options removed, credentials file stripped
        assertFalse(p.sanitized.contains("script-security"))
        assertFalse(p.sanitized.contains("update-resolv-conf"))
        assertFalse(p.sanitized.contains("block-outside-dns"))
        assertFalse(p.sanitized.contains("creds.txt"))
        assertTrue(p.sanitized.contains("\nauth-user-pass\n"))
        assertTrue(p.sanitized.contains("<tls-auth>\n-----BEGIN OpenVPN Static key V1-----"))
        assertTrue(p.warnings.any { it.contains("script-security") })
    }

    @Test fun runtimeConfigAddsManagementAndResolvedIps() {
        val p = OvpnConfig.parse(typical)
        val rt = OvpnConfig.runtimeConfig(p, "/data/cache/ovpn-mgmt", mapOf("vpn.example.com" to "198.51.100.7"), "ProxyFlow 1.1")
        assertTrue(rt.contains("remote 198.51.100.7 1194\n"))
        assertTrue(rt.contains("remote 203.0.113.9 443 tcp\n"))
        assertTrue(rt.contains("management /data/cache/ovpn-mgmt unix\nmanagement-client\nmanagement-query-passwords\nmanagement-hold\n"))
        assertTrue(rt.startsWith("# Generated by ProxyFlow\ndev tun\n"))
    }

    @Test fun rejectsExternalFilesTapAndMissingRemote() {
        val ext = OvpnConfig.parse("client\ndev tun\nremote a.example 1194\nca ca.crt\ncert client.crt\nkey client.key\n")
        assertTrue(ext.errors.any { it.contains("ca ca.crt") })
        assertTrue(ext.errors.any { it.contains("key client.key") })
        val tap = OvpnConfig.parse("client\ndev tap0\nremote a.example\n$ca")
        assertTrue(tap.errors.any { it.contains("TAP") })
        val none = OvpnConfig.parse("client\ndev tun\n$ca")
        assertTrue(none.errors.any { it.contains("remote") })
    }

    @Test fun detectsEncryptedKeyAndInlineCredentials() {
        val c = "client\ndev tun\nremote a.example 1194 udp\n$ca<key>\n-----BEGIN ENCRYPTED PRIVATE KEY-----\nxyz\n-----END ENCRYPTED PRIVATE KEY-----\n</key>\n" +
            "auth-user-pass\n<auth-user-pass>\nuser\npass\n</auth-user-pass>\n"
        val p = OvpnConfig.parse(c)
        assertTrue(p.errors.isEmpty())
        assertTrue(p.keyEncrypted)
        assertFalse("inline credentials need no prompt", p.needsUserPass)
    }

    @Test fun connectionBlocksAndDefaults() {
        val c = "client\ndev tun\nport 1195\nproto tcp-client\n<connection>\nremote one.example\n</connection>\n<connection>\nremote two.example 8443 udp\n</connection>\n$ca"
        val p = OvpnConfig.parse(c)
        assertEquals(OvpnConfig.Remote("one.example", 1195, "tcp-client"), p.remotes[0])
        assertEquals(OvpnConfig.Remote("two.example", 8443, "udp"), p.remotes[1])
        assertTrue(p.sanitized.contains("<connection>\nremote one.example 1195\n</connection>"))
    }

    @Test fun validatorRequiresCredentials() {
        val prof = ProxyProfile(name = "o", protocol = Protocol.OPENVPN, ovpnConfig = typical)
        assertTrue(ProfileValidator.validate(prof).any { it.contains("username") })
        assertTrue(ProfileValidator.validate(prof.copy(username = "u", password = "p")).isEmpty())
    }

    @Test fun tokenizerAndCidr() {
        assertEquals(listOf("remote", "host name", "1194"), OvpnConfig.tokenize("remote \"host name\" 1194 # comment"))
        assertEquals(24, OvpnConfig.maskToPrefix("255.255.255.0"))
        assertEquals(null, OvpnConfig.maskToPrefix("255.0.255.0"))
        assertEquals("10.8.0.0", OvpnConfig.networkAddress("10.8.0.6", 24))
        assertTrue(OvpnConfig.overlaps("10.0.0.0", 8, "10.8.0.0", 24))
        assertFalse(OvpnConfig.overlaps("192.168.0.0", 16, "10.8.0.0", 24))
        assertTrue(OvpnConfig.cidrContains("172.16.0.0", 12, "172.20.1.1"))
    }

    @Test fun hardResetPacketShape() {
        val pkt = OpenVpnProbe.hardReset()
        assertEquals(14, pkt.size)
        assertEquals(0x38, pkt[0].toInt() and 0xFF)
    }
}
